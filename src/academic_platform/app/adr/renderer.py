"""Renderers producing markdown output for the ADR index and CLI reports.

Rendering is separated from the registry so that both the generator script
and the query tool can share the same output rules. The renderer never
mutates the registry or the ADR records.
"""

from __future__ import annotations

from academic_platform.app.adr.model import ADR, ADRStatus
from academic_platform.app.adr.registry import ADRRegistry

_STATUS_ORDER: tuple[ADRStatus, ...] = (
    ADRStatus.ACCEPTED,
    ADRStatus.PROPOSED,
    ADRStatus.REJECTED,
    ADRStatus.DEPRECATED,
    ADRStatus.SUPERSEDED,
)


def _escape_cell(value: str) -> str:
    """Escape pipe characters that would break markdown tables."""
    return value.replace("|", "\\|").strip()


def render_index(registry: ADRRegistry) -> str:
    """Render the ADR index as markdown."""
    lines: list[str] = []
    lines.append("# Architecture Decision Records")
    lines.append("")
    lines.append(
        "This index is generated by `scripts/adr.py index`. Do not edit it "
        "manually. Add or modify ADR files under `docs/adr/` and regenerate."
    )
    lines.append("")

    counts = {status: len(registry.by_status(status)) for status in ADRStatus}
    lines.append("## Summary")
    lines.append("")
    lines.append(f"- Total records: {len(registry.records)}")
    for status in _STATUS_ORDER:
        lines.append(f"- {status.value.capitalize()}: {counts[status]}")
    if registry.errors:
        lines.append(f"- **Unparseable files**: {len(registry.errors)}")
    lines.append("")

    if registry.errors:
        lines.append("## Files requiring attention")
        lines.append("")
        for path, message in registry.errors:
            lines.append(f"- `{path.name}`: {message}")
        lines.append("")

    lines.append("## Records")
    lines.append("")
    if not registry.records:
        lines.append("_No ADRs recorded._")
        lines.append("")
        return "\n".join(lines)

    lines.append("| Number | Title | Status | Date | Superseded by |")
    lines.append("| --- | --- | --- | --- | --- |")
    for record in registry.records:
        superseded_by = record.superseded_by or "—"
        lines.append(
            "| {number} | {title} | {status} | {date} | {superseded_by} |".format(
                number=record.number,
                title=_escape_cell(record.title),
                status=record.status.value,
                date=record.date,
                superseded_by=superseded_by,
            )
        )
    lines.append("")
    return "\n".join(lines)


def render_detail(record: ADR) -> str:
    """Render a single ADR in a human-readable markdown report."""
    lines: list[str] = []
    lines.append(f"# ADR {record.number} — {record.title}")
    lines.append("")
    lines.append(f"- Status: {record.status.value}")
    lines.append(f"- Date: {record.date}")
    if record.deciders:
        lines.append(f"- Deciders: {', '.join(record.deciders)}")
    if record.supersedes:
        lines.append(f"- Supersedes: {', '.join(record.supersedes)}")
    if record.superseded_by:
        lines.append(f"- Superseded by: {record.superseded_by}")
    if record.source_path is not None:
        lines.append(f"- Source: `{record.source_path.name}`")
    lines.append("")

    for heading, content in (
        ("Context", record.context),
        ("Decision", record.decision),
        ("Consequences", record.consequences),
        ("Alternatives", record.alternatives),
    ):
        if content:
            lines.append(f"## {heading}")
            lines.append("")
            lines.append(content)
            lines.append("")

    if record.references:
        lines.append("## References")
        lines.append("")
        for reference in record.references:
            lines.append(f"- {reference}")
        lines.append("")

    for name, content in record.extra_sections:
        lines.append(f"## {name}")
        lines.append("")
        lines.append(content)
        lines.append("")

    return "\n".join(lines)