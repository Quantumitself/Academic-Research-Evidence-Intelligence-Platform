"""Application service for the research-history workspace.

The service proposes alternative search queries from the topic and its
synonyms, executes them against the search orchestration service,
persists the retrieved results, and groups the results into a timeline
and a set of themes.

Design decisions
----------------
- The service composes the search orchestration service and the
  publication service. It never speaks HTTP directly; the
  orchestration service owns the transport.
- The service never fabricates results. When a query fails, the run is
  recorded with a failure status and the source reports are preserved.
- The service is deterministic for a given topic, synonym set, and
  search response. The query generator applies a fixed set of
  templates.
- The service persists the workspace draft in the project's metadata
  under the ``research_history_workspace`` key. The retrieved results
  are also written through the publication service so that they are
  available to the rest of the application.
- Themes are generated by a deterministic rule set over titles,
  abstracts, and concepts. The rule set is documented in this module.
- The service never commits. It runs inside a unit of work supplied
  by the caller.
"""

