class ResearchHistoryService:
    """Application service for the research-history workspace."""

    def __init__(
        self,
        repositories: RepositoryManager,
        orchestrator_factory=None,
    ) -> None:
        self._repositories = repositories
        self._orchestrator_factory = orchestrator_factory

    # ------------------------------------------------------------------
    # Attachment
    # ------------------------------------------------------------------
    def attach_project(self, project_key: str) -> ResearchHistoryDraft:
        """Attach the workspace to a project."""
        project = self._require_project(project_key)
        if not _load_workspace(project).get("topic"):
            # Mirror the project's topic into the workspace on first
            # attachment, if the workspace has no topic of its own.
            metadata = _parse_metadata(project.project_metadata)
            workspace = metadata.get(_METADATA_KEY)
            if not isinstance(workspace, dict):
                workspace = {}
            if project.topic and not workspace.get("topic"):
                workspace["topic"] = project.topic
                self._write_workspace(project, workspace)
        return self.current_draft(project_key)

    # ------------------------------------------------------------------
    # Reads
    # ------------------------------------------------------------------
    def current_draft(self, project_key: str) -> ResearchHistoryDraft:
        """Return the current workspace draft."""
        project = self._require_project(project_key)
        workspace = _load_workspace(project)
        topic = str(workspace.get("topic") or "")
        synonyms = tuple(
            str(item)
            for item in (workspace.get("synonyms") or [])
            if isinstance(item, str)
        )
        queries = _load_queries(workspace)
        runs = _load_runs(workspace)
        results = _load_results(workspace)
        timeline = _build_timeline(results)
        themes = _build_themes(results)
        narrative = str(workspace.get("narrative") or "")
        return ResearchHistoryDraft(
            project_key=project.key,
            topic=topic,
            synonyms=synonyms,
            queries=queries,
            runs=runs,
            results=results,
            timeline=timeline,
            themes=themes,
            narrative=narrative,
        )

    def propose_queries(self, project_key: str) -> list[HistoryQuery]:
        """Return the queries the workspace proposes for the topic.

        The proposal is deterministic for a given topic and synonym set.
        The user may add their own queries; both are executed together.
        """
        project = self._require_project(project_key)
        workspace = _load_workspace(project)
        topic = str(workspace.get("topic") or "").strip()
        if not topic:
            return []
        user_queries = _load_queries(workspace)
        proposed: list[HistoryQuery] = []
        for template, rationale in _QUERY_TEMPLATES:
            text = template.format(topic=topic).strip()
            proposed.append(
                HistoryQuery(
                    identifier=_query_identifier(text),
                    text=text,
                    rationale=rationale,
                )
            )
        for synonym in _load_synonyms(workspace):
            proposed.append(
                HistoryQuery(
                    identifier=_query_identifier(synonym),
                    text=synonym,
                    rationale=f"Synonym search for {topic!r}.",
                )
            )
        # The user's queries are always present so that they participate
        # in the next run.
        combined = list(user_queries) + proposed
        # Deduplicate by identifier, keeping the first occurrence.
        seen: set[str] = set()
        unique: list[HistoryQuery] = []
        for query in combined:
            if query.identifier in seen:
                continue
            seen.add(query.identifier)
            unique.append(query)
        return unique[:_MAX_QUERIES]

    # ------------------------------------------------------------------
    # Workspace writes
    # ------------------------------------------------------------------
    def set_topic(self, project_key: str, topic: str) -> ResearchHistoryDraft:
        cleaned = topic.strip()
        if len(cleaned) > 1024:
            raise ResearchHistoryValidationError(
                ["Topic must be at most 1024 characters"]
            )
        project = self._require_project(project_key)
        workspace = _load_workspace(project)
        if cleaned:
            workspace["topic"] = cleaned
        else:
            workspace.pop("topic", None)
        self._write_workspace(project, workspace)
        self._record_audit(
            project_key,
            action=_ACTION_HISTORY_TOPIC_SET,
            summary=f"Topic set to {cleaned[:80]!r}",
        )
        return self.current_draft(project_key)

    def add_synonym(self, project_key: str, synonym: str) -> ResearchHistoryDraft:
        cleaned = synonym.strip()
        if not cleaned:
            raise ResearchHistoryValidationError(
                ["Synonym must not be empty"]
            )
        if len(cleaned) > 256:
            raise ResearchHistoryValidationError(
                ["Synonym must be at most 256 characters"]
            )
        project = self._require_project(project_key)
        workspace = _load_workspace(project)
        synonyms = list(workspace.get("synonyms") or [])
        if cleaned in synonyms:
            return self.current_draft(project_key)
        if len(synonyms) >= _MAX_SYNONYMS:
            raise ResearchHistoryValidationError(
                [f"At most {_MAX_SYNONYMS} synonyms are permitted"]
            )
        synonyms.append(cleaned)
        workspace["synonyms"] = synonyms
        self._write_workspace(project, workspace)
        self._record_audit(
            project_key,
            action=_ACTION_HISTORY_SYNONYM_ADDED,
            summary=f"Added synonym {cleaned[:80]!r}",
        )
        return self.current_draft(project_key)

    def remove_synonym(
        self, project_key: str, synonym: str
    ) -> ResearchHistoryDraft:
        project = self._require_project(project_key)
        workspace = _load_workspace(project)
        synonyms = [
            item
            for item in (workspace.get("synonyms") or [])
            if isinstance(item, str) and item != synonym
        ]
        workspace["synonyms"] = synonyms
        self._write_workspace(project, workspace)
        self._record_audit(
            project_key,
            action=_ACTION_HISTORY_SYNONYM_REMOVED,
            summary=f"Removed synonym {synonym[:80]!r}",
        )
        return self.current_draft(project_key)

    def add_user_query(
        self, project_key: str, text: str, *, rationale: str = ""
    ) -> ResearchHistoryDraft:
        cleaned = text.strip()
        if not cleaned:
            raise ResearchHistoryValidationError(
                ["Query must not be empty"]
            )
        if len(cleaned) > 512:
            raise ResearchHistoryValidationError(
                ["Query must be at most 512 characters"]
            )
        project = self._require_project(project_key)
        workspace = _load_workspace(project)
        queries = list(workspace.get("queries") or [])
        identifier = _query_identifier(cleaned)
        if any(
            isinstance(item, dict) and item.get("identifier") == identifier
            for item in queries
        ):
            return self.current_draft(project_key)
        queries.append(
            {
                "identifier": identifier,
                "text": cleaned,
                "rationale": rationale,
                "is_user_defined": True,
            }
        )
        workspace["queries"] = queries
        self._write_workspace(project, workspace)
        self._record_audit(
            project_key,
            action=_ACTION_HISTORY_QUERY_ADDED,
            summary=f"Added query {cleaned[:80]!r}",
        )
        return self.current_draft(project_key)

    def remove_user_query(
        self, project_key: str, identifier: str
    ) -> ResearchHistoryDraft:
        project = self._require_project(project_key)
        workspace = _load_workspace(project)
        queries = [
            item
            for item in (workspace.get("queries") or [])
            if isinstance(item, dict)
            and item.get("identifier") != identifier
        ]
        workspace["queries"] = queries
        self._write_workspace(project, workspace)
        self._record_audit(
            project_key,
            action=_ACTION_HISTORY_QUERY_REMOVED,
            summary=f"Removed query {identifier!r}",
        )
        return self.current_draft(project_key)

    def set_narrative(
        self, project_key: str, narrative: str
    ) -> ResearchHistoryDraft:
        cleaned = narrative.strip()
        if len(cleaned) > 16384:
            raise ResearchHistoryValidationError(
                ["Narrative must be at most 16384 characters"]
            )
        project = self._require_project(project_key)
        workspace = _load_workspace(project)
        if cleaned:
            workspace["narrative"] = cleaned
        else:
            workspace.pop("narrative", None)
        self._write_workspace(project, workspace)
        self._record_audit(
            project_key,
            action=_ACTION_HISTORY_NARRATIVE_UPDATED,
            summary="Narrative updated",
        )
        return self.current_draft(project_key)

    def clear(self, project_key: str) -> ResearchHistoryDraft:
        project = self._require_project(project_key)
        workspace: dict[str, Any] = {}
        self._write_workspace(project, workspace)
        self._record_audit(
            project_key,
            action=_ACTION_HISTORY_CLEARED,
            summary="Cleared the research-history workspace",
        )
        return self.current_draft(project_key)

    # ------------------------------------------------------------------
    # Search
    # ------------------------------------------------------------------
    def run_query(
        self,
        project_key: str,
        query: HistoryQuery,
    ) -> HistorySearchRun:
        """Execute a single query and persist the run and its results."""
        project = self._require_project(project_key)
        if self._orchestrator_factory is None:
            raise ResearchHistorySearchError(
                "Search orchestration is not available in this session."
            )
        orchestrator = self._orchestrator_factory()
        request = SearchOrchestrationRequest(
            search_request=SearchRequest(query=query.text, limit=_DEFAULT_LIMIT),
            selection=SourceSelection(all_enabled=True),
            session_scope="remote",
            record_session=True,
        )
        try:
            response = orchestrator.execute(request)
        except Exception as exc:  # noqa: BLE001 - boundary
            raise ResearchHistorySearchError(
                f"Search orchestration failed: {exc}"
            ) from exc

        result_keys: list[str] = []
        try:
            publications = _publications_from_response(response)
        except Exception as exc:  # noqa: BLE001 - boundary
            raise ResearchHistorySearchError(
                f"Unable to read publications from the response: {exc}"
            ) from exc
        publication_service = PublicationService(self._repositories)
        try:
            stored = publication_service.persist(tuple(publications))
        except RepositoryError as exc:
            raise ResearchHistorySearchError(
                f"Unable to persist the retrieved publications: {exc}"
            ) from exc
        for publication, row in zip(publications, stored):
            result_keys.append(publication.key)

        status = _status_from_response(response)
        source_reports = tuple(response.outcomes)
        run = HistorySearchRun(
            query_identifier=query.identifier,
            query_text=query.text,
            status=status,
            result_keys=tuple(result_keys),
            source_reports=source_reports,
            message=getattr(response, "message", "") or "",
            executed_at=dt.datetime.now(dt.timezone.utc).isoformat(),
        )

        workspace = _load_workspace(project)
        _append_run(workspace, run)
        _merge_results(workspace, publications)
        self._write_workspace(project, workspace)
        self._record_audit(
            project_key,
            action=_ACTION_HISTORY_RUN_COMPLETED,
            summary=(
                f"Query {query.text[:80]!r}: "
                f"{run.result_count} result(s), {run.status.display_name}"
            ),
        )
        return run

    def run_all(self, project_key: str) -> list[HistorySearchRun]:
        """Execute every proposed and user-defined query."""
        project = self._require_project(project_key)
        queries = self.propose_queries(project_key)
        runs: list[HistorySearchRun] = []
        for query in queries:
            try:
                run = self.run_query(project_key, query)
            except ResearchHistorySearchError as exc:
                run = HistorySearchRun(
                    query_identifier=query.identifier,
                    query_text=query.text,
                    status=HistorySearchStatus.FAILED,
                    result_keys=(),
                    source_reports=tuple(getattr(exc, "source_reports", ()) or ()),
                    message=str(exc),
                    executed_at=dt.datetime.now(dt.timezone.utc).isoformat(),
                )
                workspace = _load_workspace(project)
                _append_run(workspace, run)
                self._write_workspace(project, workspace)
            runs.append(run)
        return runs

    # ------------------------------------------------------------------
    # Internals
    # ------------------------------------------------------------------
    def _require_project(self, key: str) -> ResearchProject:
        repo = self._repositories.get("research_project")
        try:
            row = repo.find_by_key(key)
        except RepositoryError as exc:
            raise ResearchHistoryError(
                f"Unable to read the project: {exc}"
            ) from exc
        if row is None:
            raise ResearchHistoryNotFoundError(
                f"No project with key {key!r}"
            )
        return row

    def _write_workspace(self, project: ResearchProject, workspace: dict) -> None:
        metadata = _parse_metadata(project.project_metadata)
        if workspace:
            metadata[_METADATA_KEY] = workspace
        else:
            metadata.pop(_METADATA_KEY, None)
        payload = ResearchProjectUpdate(
            project_metadata=(
                json.dumps(metadata, sort_keys=True) if metadata else None
            )
        )
        try:
            self._repositories.get("research_project").update(project, payload)
        except RepositoryError as exc:
            raise ResearchHistoryError(
                f"Unable to persist the research-history workspace: {exc}"
            ) from exc

    def _record_audit(
        self,
        project_key: str,
        *,
        action: str,
        summary: str,
    ) -> None:
        try:
            session = self._repositories.get("audit_event").session
            session.add(
                AuditEvent(
                    actor="system",
                    action=action,
                    target_type="research_project",
                    target_identifier=project_key,
                    summary=summary,
                )
            )
            session.flush()
        except Exception as exc:  # noqa: BLE001 - boundary
            _logger.warning(
                "Unable to record the audit event for %s: %s",
                project_key,
                exc,
            )


# ----------------------------------------------------------------------
# Workspace serialization
# ----------------------------------------------------------------------
def _parse_metadata(raw: str | None) -> dict:
    if not raw:
        return {}
    try:
        parsed = json.loads(raw)
    except ValueError:
        return {}
    if not isinstance(parsed, dict):
        return {}
    return dict(parsed)


def _load_workspace(project: ResearchProject) -> dict:
    metadata = _parse_metadata(project.project_metadata)
    workspace = metadata.get(_METADATA_KEY)
    if not isinstance(workspace, dict):
        return {}
    # Return a deep-ish copy so that callers may mutate it.
    return json.loads(json.dumps(workspace))


def _load_synonyms(workspace: dict) -> list[str]:
    return [
        str(item)
        for item in (workspace.get("synonyms") or [])
        if isinstance(item, str) and item.strip()
    ]


def _load_queries(workspace: dict) -> tuple[HistoryQuery, ...]:
    queries: list[HistoryQuery] = []
    for item in workspace.get("queries") or []:
        if not isinstance(item, dict):
            continue
        identifier = str(item.get("identifier") or "").strip()
        text = str(item.get("text") or "").strip()
        if not identifier or not text:
            continue
        queries.append(
            HistoryQuery(
                identifier=identifier,
                text=text,
                rationale=str(item.get("rationale") or ""),
                is_user_defined=bool(item.get("is_user_defined")),
            )
        )
    return tuple(queries)


def _load_runs(workspace: dict) -> tuple[HistorySearchRun, ...]:
    runs: list[HistorySearchRun] = []
    for item in workspace.get("runs") or []:
        if not isinstance(item, dict):
            continue
        query_identifier = str(item.get("query_identifier") or "")
        query_text = str(item.get("query_text") or "")
        raw_status = str(item.get("status") or HistorySearchStatus.SKIPPED.value)
        try:
            status = HistorySearchStatus(raw_status)
        except ValueError:
            status = HistorySearchStatus.SKIPPED
        result_keys = tuple(
            str(key)
            for key in (item.get("result_keys") or [])
            if isinstance(key, str)
        )
        runs.append(
            HistorySearchRun(
                query_identifier=query_identifier,
                query_text=query_text,
                status=status,
                result_keys=result_keys,
                source_reports=(),
                message=str(item.get("message") or ""),
                executed_at=str(item.get("executed_at") or ""),
            )
        )
    return tuple(runs)


def _load_results(workspace: dict) -> tuple[HistoryResult, ...]:
    results: list[HistoryResult] = []
    for item in workspace.get("results") or []:
        if not isinstance(item, dict):
            continue
        key = str(item.get("publication_key") or "").strip()
        if not key:
            continue
        results.append(
            HistoryResult(
                publication_key=key,
                title=str(item.get("title") or ""),
                authors=tuple(
                    str(author)
                    for author in (item.get("authors") or [])
                    if isinstance(author, str)
                ),
                year=_optional_int(item.get("year")),
                venue=str(item.get("venue") or ""),
                doi=str(item.get("doi") or "") or None,
                abstract=str(item.get("abstract") or ""),
                source_providers=tuple(
                    str(provider)
                    for provider in (item.get("source_providers") or [])
                    if isinstance(provider, str)
                ),
                citation_count=_optional_int(item.get("citation_count")),
            )
        )
    return tuple(results)


def _append_run(workspace: dict, run: HistorySearchRun) -> None:
    runs = list(workspace.get("runs") or [])
    runs.append(
        {
            "query_identifier": run.query_identifier,
            "query_text": run.query_text,
            "status": run.status.value,
            "result_keys": list(run.result_keys),
            "message": run.message,
            "executed_at": run.executed_at,
        }
    )
    workspace["runs"] = runs


def _merge_results(
    workspace: dict,
    publications: tuple[CanonicalPublication, ...],
) -> None:
    existing = {
        item.get("publication_key"): item
        for item in (workspace.get("results") or [])
        if isinstance(item, dict) and item.get("publication_key")
    }
    for publication in publications:
        existing[publication.key] = {
            "publication_key": publication.key,
            "title": publication.title,
            "authors": list(publication.authors),
            "year": publication.year,
            "venue": publication.venue,
            "doi": publication.doi,
            "abstract": publication.abstract,
            "source_providers": list(publication.source_providers),
            "citation_count": publication.citation_count,
        }
    workspace["results"] = list(existing.values())


# ----------------------------------------------------------------------
# Response conversion
# ----------------------------------------------------------------------
def _publications_from_response(response) -> tuple[CanonicalPublication, ...]:
    # The orchestration response carries canonical publications directly.
    publications = getattr(response, "publications", ())
    return tuple(publications)


def _status_from_response(response) -> HistorySearchStatus:
    outcomes = getattr(response, "outcomes", ()) or ()
    if not outcomes:
        return HistorySearchStatus.SKIPPED
    has_ok = any(outcome.status is SourceOutcomeStatus.OK for outcome in outcomes)
    has_failure = any(
        outcome.status is SourceOutcomeStatus.FAILED for outcome in outcomes
    )
    if has_ok and has_failure:
        return HistorySearchStatus.PARTIAL
    if has_ok:
        return HistorySearchStatus.OK
    if has_failure:
        return HistorySearchStatus.FAILED
    return HistorySearchStatus.SKIPPED


def _query_identifier(text: str) -> str:
    import hashlib

    digest = hashlib.sha1(text.strip().lower().encode("utf-8")).hexdigest()[:16]
    return f"q.{digest}"


def _optional_int(value) -> int | None:
    if value is None:
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


# ----------------------------------------------------------------------
# Timeline and theme aggregation
# ----------------------------------------------------------------------
def _build_timeline(results: tuple[HistoryResult, ...]) -> tuple[HistoryTimelineBucket, ...]:
    buckets: dict[int, list[str]] = {}
    for result in results:
        if result.year is None:
            continue
        buckets.setdefault(result.year, []).append(result.publication_key)
    return tuple(
        HistoryTimelineBucket(
            year=year,
            result_keys=tuple(sorted(buckets[year])),
        )
        for year in sorted(buckets)
    )


_THEME_KEYWORDS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("Measurement", ("measure", "instrument", "scale", "psychometric", "invariance")),
    ("Theory", ("theor", "framework", "model", "concept")),
    ("Methods", ("method", "design", "analysis", "statistic")),
    ("Population", ("population", "sample", "cohort", "participant")),
    ("Longitudinal", ("longitud", "panel", "time-series", "trajectory")),
    ("Cross-cultural", ("cross-cultural", "cultural", "country", "nation")),
    ("Intervention", ("intervention", "trial", "treatment", "experiment")),
    ("Review", ("review", "meta-analysis", "synthesis")),
)


def _build_themes(
    results: tuple[HistoryResult, ...],
) -> tuple[HistoryTheme, ...]:
    buckets: dict[str, list[str]] = {}
    for result in results:
        haystack = " ".join(
            (
                result.title,
                result.abstract,
                result.venue,
            )
        ).lower()
        matched = False
        for theme_name, keywords in _THEME_KEYWORDS:
            if any(_keyword_match(haystack, keyword) for keyword in keywords):
                buckets.setdefault(theme_name, []).append(result.publication_key)
                matched = True
        if not matched:
            buckets.setdefault("Other", []).append(result.publication_key)
    themes: list[HistoryTheme] = []
    for theme_name in sorted(buckets):
        themes.append(
            HistoryTheme(
                name=theme_name,
                result_keys=tuple(sorted(buckets[theme_name])),
                rationale=_THEME_RATIONALE.get(theme_name, ""),
            )
        )
    return tuple(themes)


_THEME_RATIONALE: dict[str, str] = {
    "Measurement": "Papers whose titles or abstracts reference measurement.",
    "Theory": "Papers that reference theoretical constructs.",
    "Methods": "Papers that discuss research methods.",
    "Population": "Papers that focus on a specific population.",
    "Longitudinal": "Papers that use longitudinal designs.",
    "Cross-cultural": "Papers that compare across cultures or countries.",
    "Intervention": "Papers that evaluate an intervention.",
    "Review": "Review articles and syntheses.",
    "Other": "Papers that did not match any keyword.",
}


def _keyword_match(haystack: str, keyword: str) -> bool:
    return re.search(rf"\b{re.escape(keyword)}", haystack) is not None